from kernel.block import Block


class Supervisor(Block):
    """
    SUPERVISOR
    ==========

    Inputs
    ------
    statistics:
        Regime descriptor generated from trajectory,
        estimator and ratchet histories.

    policy_library:
        Candidate estimator/controller parameter sets
        generated by Q-SYNTH offline synthesis.

    Outputs
    -------
    active_policy:
        Selected Policy object.

    Function
    --------
    Operates on a much slower time scale than the
    feedback controller.

    Responsibilities
    ----------------
    1. monitor statistical behaviour;
    2. detect persistent regime change;
    3. select appropriate policy;
    4. update estimator/controller parameters.

    State-machine interpretation
    ----------------------------
    INITIALIZE
        ->
    MONITOR
        ->
    REGIME_CHANGE
        ->
    SELECT_POLICY
        ->
    APPLY_POLICY
        ->
    MONITOR

    Initial demonstration
    ---------------------
    Uses excess kurtosis as a simple example regime
    indicator.

    This is deliberately only a placeholder for future
    statistically justified regime classification.
    """

    def __init__(
        self,
        period,
        policy_library,
        estimator,
        controller
    ):

        super().__init__(
            name="Supervisor",
            period=period,
            priority=70
        )

        self.policy_library = (
            policy_library
        )

        self.estimator = estimator
        self.controller = controller

        self.state = "INITIALIZE"

        self.active_policy = None


    def apply_policy(
        self,
        policy,
        t,
        bus
    ):

        self.estimator.set_parameters(
            policy.Q_eff,
            policy.R_eff
        )

        self.controller.set_parameters(
            policy.alpha,
            policy.XT
        )

        self.active_policy = policy

        bus.publish(
            "active_policy",
            policy,
            t
        )


    def update(
        self,
        t,
        bus
    ):

        statistics = bus.read(
            "statistics"
        )

        if self.active_policy is None:

            self.apply_policy(
                self.policy_library[
                    "nominal"
                ],
                t,
                bus
            )

            self.state = "MONITOR"

            return


        if statistics is None:
            return


        kurtosis = (
            statistics[
                "relative_excess_kurtosis"
            ]
        )


        # -----------------------------------------------
        # Example only:
        #
        # large persistent tail statistics -> robust set
        # -----------------------------------------------

        if abs(kurtosis) > 1.0:

            selected = (
                self.policy_library[
                    "robust"
                ]
            )

            self.state = (
                "REGIME_CHANGE"
            )

        else:

            selected = (
                self.policy_library[
                    "nominal"
                ]
            )

            self.state = (
                "MONITOR"
            )


        if (
            self.active_policy.name
            != selected.name
        ):

            self.state = (
                "APPLY_POLICY"
            )

            self.apply_policy(
                selected,
                t,
                bus
            )
